    expectTypeOf<Sdk.StackPayload>().toEqualTypeOf<Rules.StackPayload>();
    expectTypeOf<Sdk.StackAnswer>().toEqualTypeOf<Rules.StackAnswer>();
    expectTypeOf<Sdk.HeapParams>().toEqualTypeOf<Rules.HeapParams>();
